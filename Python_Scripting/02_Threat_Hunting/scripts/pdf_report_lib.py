"""
pdf_report_lib.py

Shared PDF report builder used by every analyze_*.py script in this
activity. Renders a titled, multi-section incident report with tables,
a simple hand-drawn bar chart, and page numbers, using fpdf2.

If fpdf2 is not installed, it is installed automatically with pip the
first time a script that imports this module is run.
"""

import subprocess
import sys


def _pip_install(package):
    """Tries a plain pip install first, then falls back to the flag
    combinations needed on PEP 668 "externally managed" systems (Debian/
    Kali/Ubuntu) and no-write-access user installs, in that order, so this
    works unattended across venvs, system Python, and locked-down distros."""
    attempts = [
        [sys.executable, "-m", "pip", "install", "--quiet", package],
        [sys.executable, "-m", "pip", "install", "--quiet", "--break-system-packages", package],
        [sys.executable, "-m", "pip", "install", "--quiet", "--user", package],
        [sys.executable, "-m", "pip", "install", "--quiet", "--user", "--break-system-packages", package],
    ]
    last_result = None
    for cmd in attempts:
        last_result = subprocess.run(cmd, capture_output=True, text=True)
        if last_result.returncode == 0:
            return True
    print(last_result.stdout)
    print(last_result.stderr)
    return False


def _ensure_fpdf():
    try:
        import fpdf  # noqa: F401
        return fpdf
    except ImportError:
        print("[pdf_report_lib] fpdf2 not found, installing it now (pip install fpdf2)...")
        if not _pip_install("fpdf2"):
            raise RuntimeError(
                "Could not automatically install fpdf2. Install it manually with: "
                "python -m pip install fpdf2"
            )
        import fpdf  # noqa: F401
        return fpdf


fpdf = _ensure_fpdf()
from fpdf import FPDF  # noqa: E402

NAVY = (23, 42, 64)
RED = (191, 34, 40)
GREY = (110, 110, 110)
LIGHT_GREY = (235, 237, 240)
WHITE = (255, 255, 255)
GREEN = (30, 120, 70)


def _safe(text):
    """The core Helvetica font only supports latin-1. Any unexpected
    character from raw log data is swapped for '?' instead of crashing
    PDF generation."""
    return str(text).encode("latin-1", errors="replace").decode("latin-1")


class IncidentReport:
    """Builds a multi-section PDF incident report for a single log analysis run."""

    def __init__(self, title, subtitle, log_file, generated_by="Log Analysis Toolkit"):
        self.pdf = FPDF(orientation="P", unit="mm", format="A4")
        self.pdf.set_margins(left=15, top=15, right=15)
        self.pdf.set_auto_page_break(auto=True, margin=18)
        self.pdf.set_title(title)
        self.generated_by = generated_by
        self.log_file = log_file
        self._cover(title, subtitle)

    # ---- low level helpers -------------------------------------------------
    def _cover(self, title, subtitle):
        p = self.pdf
        p.add_page()
        p.set_fill_color(*NAVY)
        p.rect(0, 0, 210, 55, "F")
        p.set_xy(0, 16)
        p.set_font("Helvetica", "B", 22)
        p.set_text_color(*WHITE)
        p.cell(210, 12, title, align="C", new_x="LMARGIN", new_y="NEXT")
        p.set_font("Helvetica", "", 12)
        p.cell(210, 8, subtitle, align="C", new_x="LMARGIN", new_y="NEXT")
        p.set_xy(15, 65)
        p.set_text_color(0, 0, 0)
        p.set_font("Helvetica", "", 10)
        import datetime
        p.multi_cell(0, 6, _safe(f"Source log file: {self.log_file}"), new_x="LMARGIN", new_y="NEXT")
        p.cell(0, 6, f"Report generated: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}", new_x="LMARGIN", new_y="NEXT")
        p.cell(0, 6, f"Generated by: {self.generated_by}", new_x="LMARGIN", new_y="NEXT")
        p.ln(6)

    def severity_banner(self, text, level="critical"):
        p = self.pdf
        color = RED if level == "critical" else (200, 140, 20)
        p.set_fill_color(*color)
        p.set_text_color(*WHITE)
        p.set_font("Helvetica", "B", 11)
        p.multi_cell(0, 7, f"  {_safe(text)}", fill=True, align="L")
        p.set_text_color(0, 0, 0)
        p.ln(4)

    def section(self, heading):
        p = self.pdf
        if p.get_y() > 260:
            p.add_page()
        p.set_font("Helvetica", "B", 13)
        p.set_text_color(*NAVY)
        p.cell(0, 9, _safe(heading), new_x="LMARGIN", new_y="NEXT")
        p.set_draw_color(*NAVY)
        p.set_line_width(0.5)
        y = p.get_y()
        p.line(15, y, 195, y)
        p.ln(3)
        p.set_text_color(0, 0, 0)
        p.set_font("Helvetica", "", 10)

    def paragraph(self, text):
        p = self.pdf
        p.set_font("Helvetica", "", 10)
        p.multi_cell(0, 5.5, _safe(text))
        p.ln(1)

    def key_values(self, pairs):
        """pairs: list of (label, value) shown as a compact two-column table."""
        p = self.pdf
        longest = max((len(str(label)) for label, _ in pairs), default=10)
        label_w = min(90, max(55, longest * 1.9))
        value_w = p.w - p.l_margin - p.r_margin - label_w
        for label, value in pairs:
            if p.get_y() > 275:
                p.add_page()
            y_start = p.get_y()
            p.set_font("Helvetica", "B", 10)
            p.set_xy(p.l_margin, y_start)
            p.cell(label_w, 6, _safe(label))
            p.set_font("Helvetica", "", 10)
            p.set_xy(p.l_margin + label_w, y_start)
            p.multi_cell(value_w, 6, _safe(value))
        p.ln(2)

    def table(self, headers, rows, col_widths=None, max_rows=40):
        p = self.pdf
        if not rows:
            self.paragraph("(no entries found)")
            return
        rows = rows[:max_rows]
        n = len(headers)
        if col_widths is None:
            col_widths = [180 / n] * n
        p.set_font("Helvetica", "B", 9)
        p.set_fill_color(*NAVY)
        p.set_text_color(*WHITE)
        for h, w in zip(headers, col_widths):
            p.cell(w, 7, _safe(h), border=1, fill=True, align="C")
        p.ln()
        p.set_text_color(0, 0, 0)
        p.set_font("Helvetica", "", 8.5)
        fill = False
        for row in rows:
            if p.get_y() > 275:
                p.add_page()
                p.set_font("Helvetica", "B", 9)
                p.set_fill_color(*NAVY)
                p.set_text_color(*WHITE)
                for h, w in zip(headers, col_widths):
                    p.cell(w, 7, _safe(h), border=1, fill=True, align="C")
                p.ln()
                p.set_text_color(0, 0, 0)
                p.set_font("Helvetica", "", 8.5)
            p.set_fill_color(*LIGHT_GREY) if fill else p.set_fill_color(*WHITE)
            for val, w in zip(row, col_widths):
                text = _safe(val)
                if len(text) > int(w / 1.8):
                    text = text[: int(w / 1.8) - 3] + "..."
                p.cell(w, 6.5, text, border=1, fill=True)
            p.ln()
            fill = not fill
        p.ln(3)

    def bar_chart(self, title, labels, values, max_bars=10, unit=""):
        """A simple horizontal bar chart drawn with rectangles, no matplotlib needed."""
        p = self.pdf
        if not values:
            return
        pairs = list(zip(labels, values))[:max_bars]
        p.set_font("Helvetica", "B", 10)
        p.cell(0, 7, title, new_x="LMARGIN", new_y="NEXT")
        p.set_font("Helvetica", "", 8)
        max_val = max(v for _, v in pairs) or 1
        chart_left = 55
        chart_width = 110
        row_h = 6.5
        for label, value in pairs:
            if p.get_y() > 270:
                p.add_page()
            y = p.get_y()
            label_text = _safe(label)
            if len(label_text) > 28:
                label_text = label_text[:25] + "..."
            p.set_xy(15, y)
            p.cell(chart_left - 17, row_h, label_text)
            bar_w = max(1.5, (value / max_val) * chart_width)
            p.set_fill_color(*RED)
            p.rect(chart_left, y + 0.8, bar_w, row_h - 1.6, "F")
            p.set_xy(chart_left + chart_width + 2, y)
            p.cell(25, row_h, f"{value}{unit}")
            p.set_y(y + row_h)
        p.ln(3)

    def footer_note(self, text):
        self.paragraph(text)

    def save(self, path):
        self.pdf.output(path)
        return path
