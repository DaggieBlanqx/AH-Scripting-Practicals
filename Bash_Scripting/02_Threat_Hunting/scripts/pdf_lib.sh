#!/bin/bash
#
# pdf_lib.sh
#
# A small, dependency-free PDF report writer, in pure Bash. No Python,
# no Ghostscript, no pandoc, nothing but printf, grep, fold, and wc. It
# writes classic, uncompressed PDF 1.4 syntax directly: this is fully
# spec-legal PDF (streams have never been required to be compressed),
# it just means the file is a bit larger and, happily, human-readable
# if you ever want to peek inside it with a text editor.
#
# Usage from an analyze_*.sh script:
#   source "$(dirname "${BASH_SOURCE[0]}")/pdf_lib.sh"
#   pdf_init "Report Title" "Subtitle" "path/to/source.log"
#   pdf_banner "CRITICAL: something bad happened"
#   pdf_section "Executive Summary"
#   pdf_kv "Total requests" "1,234"
#   pdf_text "Some paragraph of explanation goes here."
#   pdf_table_line "$(printf '%-20s %10s' "IP" "Count")"
#   pdf_bar "1.2.3.4" 42 100
#   pdf_hr
#   pdf_save "reports/output.pdf"

export LC_ALL=C

# ---- page geometry (A4, points) ------------------------------------------
PDF_PAGE_W=595
PDF_PAGE_H=842
PDF_MARGIN=50
PDF_TOP=$((PDF_PAGE_H - PDF_MARGIN))      # 792
PDF_RIGHT=$((PDF_PAGE_W - PDF_MARGIN))    # 545
PDF_BOTTOM=$PDF_MARGIN                    # 50
PDF_USABLE_W=$((PDF_RIGHT - PDF_MARGIN))  # 495

# navy / red / grey as PDF "rg" fill-color triples (0-1 range)
PDF_COLOR_NAVY="0.09 0.16 0.25"
PDF_COLOR_RED="0.75 0.13 0.16"
PDF_COLOR_BLACK="0 0 0"
PDF_COLOR_WHITE="1 1 1"
PDF_COLOR_GREY="0.45 0.45 0.45"

# ---- internal state --------------------------------------------------
_PDF_PAGES=()      # one element per page, holds that page's content stream text
_PDF_CUR_Y=0
_PDF_TITLE=""

_pdf_new_page() {
    _PDF_PAGES+=("")
    _PDF_CUR_Y=$PDF_TOP
}

_pdf_append() {
    local idx=$((${#_PDF_PAGES[@]} - 1))
    _PDF_PAGES[$idx]="${_PDF_PAGES[$idx]}$1
"
}

_pdf_ensure_space() {
    local needed="$1"
    if [ "$((_PDF_CUR_Y - needed))" -lt "$PDF_BOTTOM" ]; then
        _pdf_new_page
    fi
}

# Escapes PDF string special characters (backslash and parens) and strips
# anything outside printable ASCII, since the standard 14 fonts only
# guarantee that range.
_pdf_escape() {
    printf '%s' "$1" | tr -cd '\40-\176' | sed -e 's/\\/\\\\/g' -e 's/(/\\(/g' -e 's/)/\\)/g'
}

# Word-wraps text to fit the usable page width for a given point size.
# Uses a conservative average-character-width estimate so nothing overflows.
_pdf_wrap() {
    local text="$1" size="${2:-10}"
    local chars_per_line=$(( PDF_USABLE_W * 2 / size ))
    if [ "$chars_per_line" -lt 10 ]; then chars_per_line=10; fi
    if [ -z "$text" ]; then
        printf '\n'
    else
        # the trailing \n before folding matters: without it, the last
        # wrapped line has no line terminator, and every "while read"
        # loop that consumes this output would silently drop that final
        # line (a classic Bash gotcha).
        printf '%s\n' "$text" | fold -s -w "$chars_per_line"
    fi
}

# ---- public API -----------------------------------------------------------

pdf_init() {
    local title="$1" subtitle="$2" source="$3"
    _PDF_PAGES=()
    _PDF_TITLE="$title"
    _pdf_new_page

    # Cover banner block (navy rectangle across the top of page 1)
    _pdf_append "$PDF_COLOR_NAVY rg"
    _pdf_append "0 $((PDF_PAGE_H - 130)) $PDF_PAGE_W 130 re f"
    _pdf_append "BT"
    _pdf_append "$PDF_COLOR_WHITE rg"
    _pdf_append "/F2 20 Tf"
    _pdf_append "1 0 0 1 $PDF_MARGIN $((PDF_PAGE_H - 60)) Tm"
    _pdf_append "($(_pdf_escape "$title")) Tj"
    _pdf_append "/F1 12 Tf"
    _pdf_append "1 0 0 1 $PDF_MARGIN $((PDF_PAGE_H - 85)) Tm"
    _pdf_append "($(_pdf_escape "$subtitle")) Tj"
    _pdf_append "ET"

    _PDF_CUR_Y=$((PDF_PAGE_H - 155))

    pdf_text "Source file: $source"
    pdf_text "Generated: $(date '+%Y-%m-%d %H:%M:%S')"
    pdf_text "Generated by: Bash Log/PCAP Analysis Toolkit (pure Bash, no external report dependencies)"
    _PDF_CUR_Y=$((_PDF_CUR_Y - 6))
}

pdf_section() {
    local heading="$1"
    _pdf_ensure_space 34
    _PDF_CUR_Y=$((_PDF_CUR_Y - 8))
    _pdf_append "BT"
    _pdf_append "$PDF_COLOR_NAVY rg"
    _pdf_append "/F2 13 Tf"
    _pdf_append "1 0 0 1 $PDF_MARGIN $_PDF_CUR_Y Tm"
    _pdf_append "($(_pdf_escape "$heading")) Tj"
    _pdf_append "ET"
    local rule_y=$((_PDF_CUR_Y - 4))
    _pdf_append "$PDF_COLOR_NAVY RG"
    _pdf_append "0.8 w"
    _pdf_append "$PDF_MARGIN $rule_y m $PDF_RIGHT $rule_y l S"
    _PDF_CUR_Y=$((_PDF_CUR_Y - 18))
}

pdf_text() {
    local text="$1"
    while IFS= read -r line; do
        _pdf_ensure_space 14
        _pdf_append "BT"
        _pdf_append "$PDF_COLOR_BLACK rg"
        _pdf_append "/F1 10 Tf"
        _pdf_append "1 0 0 1 $PDF_MARGIN $_PDF_CUR_Y Tm"
        _pdf_append "($(_pdf_escape "$line")) Tj"
        _pdf_append "ET"
        _PDF_CUR_Y=$((_PDF_CUR_Y - 14))
    done < <(_pdf_wrap "$text" 10)
}

# A pre-formatted monospace line (caller does the column alignment with
# printf, exactly like formatting a table row for terminal output).
pdf_table_line() {
    local text="$1"
    _pdf_ensure_space 12
    _pdf_append "BT"
    _pdf_append "$PDF_COLOR_BLACK rg"
    _pdf_append "/F3 8.5 Tf"
    _pdf_append "1 0 0 1 $PDF_MARGIN $_PDF_CUR_Y Tm"
    _pdf_append "($(_pdf_escape "$text")) Tj"
    _pdf_append "ET"
    _PDF_CUR_Y=$((_PDF_CUR_Y - 12))
}

pdf_table_header() {
    local text="$1"
    _pdf_ensure_space 16
    _pdf_append "$PDF_COLOR_NAVY rg"
    _pdf_append "$PDF_MARGIN $((_PDF_CUR_Y - 3)) $PDF_USABLE_W 13 re f"
    _pdf_append "BT"
    _pdf_append "$PDF_COLOR_WHITE rg"
    _pdf_append "/F3 8.5 Tf"
    _pdf_append "1 0 0 1 $((PDF_MARGIN + 3)) $_PDF_CUR_Y Tm"
    _pdf_append "($(_pdf_escape "$text")) Tj"
    _pdf_append "ET"
    _PDF_CUR_Y=$((_PDF_CUR_Y - 15))
}

pdf_kv() {
    local label="$1" value="$2"
    # A bold 10pt label wider than ~22 characters would physically overlap
    # the value column (fixed at +165pt), so long labels get their own
    # line instead of forcing a two-column layout that would collide.
    if [ "${#label}" -le 22 ]; then
        local first=1
        while IFS= read -r line; do
            _pdf_ensure_space 14
            _pdf_append "BT"
            _pdf_append "$PDF_COLOR_BLACK rg"
            if [ "$first" -eq 1 ]; then
                _pdf_append "/F2 10 Tf"
                _pdf_append "1 0 0 1 $PDF_MARGIN $_PDF_CUR_Y Tm"
                _pdf_append "($(_pdf_escape "$label")) Tj"
            fi
            _pdf_append "/F1 10 Tf"
            _pdf_append "1 0 0 1 $((PDF_MARGIN + 165)) $_PDF_CUR_Y Tm"
            _pdf_append "($(_pdf_escape "$line")) Tj"
            _pdf_append "ET"
            _PDF_CUR_Y=$((_PDF_CUR_Y - 14))
            first=0
        done < <(_pdf_wrap "$value" 10 | fold -s -w 55)
    else
        _pdf_ensure_space 14
        _pdf_append "BT"
        _pdf_append "$PDF_COLOR_BLACK rg"
        _pdf_append "/F2 10 Tf"
        _pdf_append "1 0 0 1 $PDF_MARGIN $_PDF_CUR_Y Tm"
        _pdf_append "($(_pdf_escape "$label")) Tj"
        _pdf_append "ET"
        _PDF_CUR_Y=$((_PDF_CUR_Y - 14))
        while IFS= read -r line; do
            _pdf_ensure_space 14
            _pdf_append "BT"
            _pdf_append "$PDF_COLOR_BLACK rg"
            _pdf_append "/F1 10 Tf"
            _pdf_append "1 0 0 1 $((PDF_MARGIN + 15)) $_PDF_CUR_Y Tm"
            _pdf_append "($(_pdf_escape "$line")) Tj"
            _pdf_append "ET"
            _PDF_CUR_Y=$((_PDF_CUR_Y - 14))
        done < <(_pdf_wrap "$value" 10 | fold -s -w 80)
    fi
}

pdf_banner() {
    local text="$1"
    local wrapped
    wrapped=$(_pdf_wrap "$text" 11 | fold -s -w 78)
    local n_lines
    n_lines=$(printf '%s\n' "$wrapped" | wc -l)
    local box_h=$((n_lines * 14 + 10))
    _pdf_ensure_space "$((box_h + 10))"
    _pdf_append "$PDF_COLOR_RED rg"
    _pdf_append "$PDF_MARGIN $((_PDF_CUR_Y - box_h + 14)) $PDF_USABLE_W $box_h re f"
    local line_y=$_PDF_CUR_Y
    while IFS= read -r line; do
        _pdf_append "BT"
        _pdf_append "$PDF_COLOR_WHITE rg"
        _pdf_append "/F2 11 Tf"
        _pdf_append "1 0 0 1 $((PDF_MARGIN + 8)) $line_y Tm"
        _pdf_append "($(_pdf_escape "$line")) Tj"
        _pdf_append "ET"
        line_y=$((line_y - 14))
    done <<< "$wrapped"
    _PDF_CUR_Y=$((_PDF_CUR_Y - box_h - 8))
}

# pdf_bar "label" value max_value ["unit"]
pdf_bar() {
    local label="$1" value="$2" max="$3" unit="${4:-}"
    [ "$max" -le 0 ] 2>/dev/null && max=1
    _pdf_ensure_space 16
    local label_short="$label"
    if [ "${#label_short}" -gt 26 ]; then
        label_short="${label_short:0:25}..."
    fi
    _pdf_append "BT"
    _pdf_append "$PDF_COLOR_BLACK rg"
    _pdf_append "/F1 8.5 Tf"
    _pdf_append "1 0 0 1 $PDF_MARGIN $_PDF_CUR_Y Tm"
    _pdf_append "($(_pdf_escape "$label_short")) Tj"
    _pdf_append "ET"

    local bar_x=$((PDF_MARGIN + 145))
    local bar_max_w=250
    local bar_w=$(( value * bar_max_w / max ))
    [ "$bar_w" -lt 2 ] && bar_w=2
    _pdf_append "$PDF_COLOR_RED rg"
    _pdf_append "$bar_x $((_PDF_CUR_Y - 2)) $bar_w 9 re f"

    _pdf_append "BT"
    _pdf_append "$PDF_COLOR_BLACK rg"
    _pdf_append "/F1 8.5 Tf"
    _pdf_append "1 0 0 1 $((bar_x + bar_max_w + 8)) $_PDF_CUR_Y Tm"
    _pdf_append "($(_pdf_escape "$value$unit")) Tj"
    _pdf_append "ET"
    _PDF_CUR_Y=$((_PDF_CUR_Y - 14))
}

pdf_hr() {
    _pdf_ensure_space 10
    _pdf_append "$PDF_COLOR_GREY RG"
    _pdf_append "0.5 w"
    _pdf_append "$PDF_MARGIN $_PDF_CUR_Y m $PDF_RIGHT $_PDF_CUR_Y l S"
    _PDF_CUR_Y=$((_PDF_CUR_Y - 10))
}

pdf_spacer() {
    local h="${1:-6}"
    _PDF_CUR_Y=$((_PDF_CUR_Y - h))
}

# ---- final assembly --------------------------------------------------
pdf_save() {
    local out_path="$1"
    local out_dir
    out_dir=$(dirname "$out_path")
    mkdir -p "$out_dir"

    local body
    body=$(mktemp)
    local final
    final=$(mktemp)
    trap 'rm -f "$body" "$final"' RETURN

    {
        printf '%s\n' "%PDF-1.4"

        # obj 1: Catalog
        printf '%s\n' "1 0 obj"
        printf '%s\n' "<< /Type /Catalog /Pages 2 0 R >>"
        printf '%s\n' "endobj"

        local n_pages=${#_PDF_PAGES[@]}
        local i
        local kids=""
        for ((i = 0; i < n_pages; i++)); do
            kids="$kids $((6 + i * 2)) 0 R"
        done

        # obj 2: Pages
        printf '%s\n' "2 0 obj"
        printf '%s\n' "<< /Type /Pages /Kids [$kids] /Count $n_pages >>"
        printf '%s\n' "endobj"

        # obj 3: Font Helvetica
        printf '%s\n' "3 0 obj"
        printf '%s\n' "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica /Encoding /WinAnsiEncoding >>"
        printf '%s\n' "endobj"

        # obj 4: Font Helvetica-Bold
        printf '%s\n' "4 0 obj"
        printf '%s\n' "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold /Encoding /WinAnsiEncoding >>"
        printf '%s\n' "endobj"

        # obj 5: Font Courier (used by pdf_table_line/pdf_table_header)
        printf '%s\n' "5 0 obj"
        printf '%s\n' "<< /Type /Font /Subtype /Type1 /BaseFont /Courier /Encoding /WinAnsiEncoding >>"
        printf '%s\n' "endobj"

        for ((i = 0; i < n_pages; i++)); do
            local page_obj=$((6 + i * 2))
            local content_obj=$((7 + i * 2))
            printf '%s\n' "$page_obj 0 obj"
            printf '%s\n' "<< /Type /Page /Parent 2 0 R /Resources << /Font << /F1 3 0 R /F2 4 0 R /F3 5 0 R >> >> /MediaBox [0 0 $PDF_PAGE_W $PDF_PAGE_H] /Contents $content_obj 0 R >>"
            printf '%s\n' "endobj"

            local content="${_PDF_PAGES[$i]}"
            local clen
            clen=$(printf '%s' "$content" | wc -c)
            printf '%s\n' "$content_obj 0 obj"
            printf '%s\n' "<< /Length $clen >>"
            printf '%s\n' "stream"
            printf '%s' "$content"
            printf '\n%s\n' "endstream"
            printf '%s\n' "endobj"
        done
    } > "$body"

    local offsets
    offsets=$(grep -abo '^[0-9]\+ 0 obj$' "$body" | cut -d: -f1)

    local n_objs
    n_objs=$(printf '%s\n' "$offsets" | grep -c '^[0-9]')
    local highest=$((n_objs + 1))

    {
        cat "$body"
        printf 'xref\n0 %d\n' "$highest"
        printf '0000000000 65535 f \n'
        while IFS= read -r off; do
            printf '%010d 00000 n \n' "$off"
        done <<< "$offsets"
        local startxref
        startxref=$(wc -c < "$body")
        printf 'trailer\n<< /Size %d /Root 1 0 R >>\nstartxref\n%d\n%%%%EOF\n' "$highest" "$startxref"
    } > "$out_path"

    echo "$out_path"
}
